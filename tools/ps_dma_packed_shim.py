"""Generate the Verilog module-reference shell required by Vivado BD."""
from pathlib import Path
import re
def generate():
    source=Path('rtl/ps_dma_v2/resnet20_axi_packed.sv').read_text()
    header=source[source.index('module resnet20_axi_packed('):source.index('\n);')+3]
    names=re.findall(r'(?:input wire|output (?:logic|wire))\s*(?:\[[^\]]+\]\s*)?(\w+)',header)
    header=header.replace('module resnet20_axi_packed(','module resnet20_axi_packed_bd(').replace('output logic','output wire')
    text='`timescale 1ns/1ps\n// Generated by python -m tools.ps_dma_packed_shim; BD module-reference Verilog shell.\n'+header+'\n    resnet20_axi_packed core_unit(\n'+',\n'.join('        .'+n+'('+n+')' for n in names)+'\n    );\nendmodule\n'
    Path('rtl/ps_dma_v2/resnet20_axi_packed_bd.v').write_text(text,encoding='utf-8',newline='\n')
    return len(names)
if __name__=='__main__':print('BD shell ports:',generate())
